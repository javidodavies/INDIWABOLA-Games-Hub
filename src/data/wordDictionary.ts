function sanitizeWords(list: string[]): string[] {
  const out: string[] = [];
  for (const w of list) {
    const clean = w.trim().toUpperCase();
    if (/^[A-Z]{3,}$/.test(clean)) {
      out.push(clean);
    }
  }
  return out;
}

